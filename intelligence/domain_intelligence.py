def calculate_domain_risk(domain_data: Dict[str, Any], api_failed: bool = False) -> Dict[str, Any]:
    """
    Calculates a 0-100 normalized risk score based on Domain intelligence signals.
    Fails safely if the data is unavailable or missing.
    """
    if api_failed or not domain_data:
        return {"risk_score": 0, "risk_level": "UNKNOWN", "risk_reasons": ["Domain Intel API unavailable or data missing"]}

    score = 0
    reasons = []

    # Apply Weights based on provided requirements
    if domain_data.get('is_malicious'):
        score += 50
        reasons.append("Domain blacklisted in reputation feeds")
    if domain_data.get('is_lookalike'):
        score += 50
        reasons.append("Homograph/lookalike domain detected")
    if domain_data.get('reply_to_mismatch'):
        score += 25
        reasons.append("Reply-To address does not match Sender")
    if domain_data.get('return_path_mismatch'):
        score += 20
        reasons.append("Return-Path misalignment (Authentication failure)")
    if domain_data.get('missing_mx'):
        score += 20
        reasons.append("No valid MX records found for domain")
    if domain_data.get('is_new_domain'):
        score += 20
        reasons.append("Domain registered very recently")
    if domain_data.get('suspicious_tld'):
        score += 15
        reasons.append("Suspicious Top-Level Domain (e.g., .xyz, .top)")
    if domain_data.get('body_mismatch'):
        score += 10
        reasons.append("Links in body do not match sender domain")

    # Cap at 100
    final_score = min(score, 100)
    
    # Determine Level
    level = "HIGH" if final_score >= 70 else "MEDIUM" if final_score >= 40 else "LOW"

    return {
        "risk_score": final_score,
        "risk_level": level,
        "risk_reasons": reasons
    }


def analyze_domain_intelligence(
    from_header: Optional[str],
    reply_to_header: Optional[str] = None,
    return_path_header: Optional[str] = None,
    body_urls: Optional[List[str]] = None,
    offline_mode: bool = False,
) -> Dict[str, Any]:
    """
    Main entry point for Domain Intelligence.
    Consumes header forensic domain data and body URLs, producing structured risk signals.
    """
    body_urls = body_urls or []
    brand_targets = load_brand_targets()

    from_parts = extract_domain_parts(from_header)
    reply_to_parts = extract_domain_parts(reply_to_header)
    return_path_parts = extract_domain_parts(return_path_header)

    from_domain = from_parts["registered_domain"]
    reply_to_domain = reply_to_parts["registered_domain"]
    return_path_domain = return_path_parts["registered_domain"]

    # Extract registered domains from body URLs
    body_domains = set()
    for url in body_urls:
        parts = extract_domain_parts(url)
        if parts["registered_domain"]:
            body_domains.add(parts["registered_domain"])

    # Lookalike Brand Check
    lookalike_info = detect_lookalike_brand(from_parts["domain_name"] or "", brand_targets)

    # Header Alignment
    reply_to_mismatch = bool(
        reply_to_domain and from_domain and reply_to_domain != from_domain
    )
    return_path_mismatch = bool(
        return_path_domain and from_domain and return_path_domain != from_domain
    )

    # Body Link Alignment: flag if links exist and none match the sender domain
    body_domain_mismatch = False
    if from_domain and body_domains:
        body_domain_mismatch = from_domain not in body_domains

    # Live MX Check
    has_mx = True
    mx_check_failed = False
    if from_domain and not offline_mode:
         # Simplified failure state tracking for MX check
         try:
            has_mx = check_mx_record(from_domain)
         except Exception:
             mx_check_failed = True

    # Assemble signals dictionary to pass to scoring engine
    # Note: 'is_malicious', 'is_new_domain', 'suspicious_tld' would typically come from an external reputation API.
    # We include them here as False defaults to ensure the scoring engine works, but they should be populated if you add an API call.
    signals_data = {
        "reply_to_mismatch": reply_to_mismatch,
        "return_path_mismatch": return_path_mismatch,
        "is_lookalike": lookalike_info["is_lookalike"], # Mapped to schema
        "body_mismatch": body_domain_mismatch, # Mapped to schema
        "missing_mx": not has_mx if not mx_check_failed else False, # Only flag missing if check succeeded and found none
        "is_malicious": False, # Placeholder for external API
        "is_new_domain": False, # Placeholder for external API (whois)
        "suspicious_tld": False # Placeholder, could be implemented with a static list check
    }

    # Calculate Normalized Risk Score
    risk_assessment = calculate_domain_risk(signals_data, api_failed=offline_mode)

    return {
        "status": "success",
        "domains": {
            "from_domain": from_domain,
            "reply_to_domain": reply_to_domain,
            "return_path_domain": return_path_domain,
            "body_domains": sorted(list(body_domains)),
        },
        "identity_alignment": {
            "from_matches_reply_to": not reply_to_mismatch,
            "from_matches_return_path": not return_path_mismatch,
            "from_matches_body_links": not body_domain_mismatch,
        },
        "lookalike_analysis": lookalike_info,
        "dns_health": {
            "from_has_mx": has_mx,
        },
        "signals": {
            "reply_to_mismatch": reply_to_mismatch,
            "return_path_mismatch": return_path_mismatch,
            "is_brand_lookalike": lookalike_info["is_lookalike"],
            "body_domain_mismatch": body_domain_mismatch,
            "from_missing_mx": not has_mx,
        },
        "normalized_output": risk_assessment # Appended without breaking old schema
    }